/** 按用户提供的完整题库截图显示问题编码及完整内容；未知编码保留原值。 */
export function formatAppleIdSecurityQuestion(value) {
  if (value === null || value === undefined || value === '') return '—';
  const code = String(value);
  const content = QUESTION_LABELS[code];
  return content ? `${code} / ${content}` : code;
}
